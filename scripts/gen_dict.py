def build_assoc() -> dict[str, list[str]]:
    """解析联想词库：'前词: 联想1 联想2 ...'（ASSOC 与 ASSOC_EXTRA 合并）"""
    result: dict[str, list[str]] = {}
    for block in (ASSOC, ASSOC_EXTRA):
        for line in block.strip().splitlines():
            line = line.strip()
            if not line or ":" not in line:
                continue
            key, rest = line.split(":", 1)
            key = key.strip()
            if not key:
                continue
            bucket = result.setdefault(key, [])
            for word in rest.split():
                word = word.strip()
                if word and word != key and word not in bucket:
                    bucket.append(word)
    return result


