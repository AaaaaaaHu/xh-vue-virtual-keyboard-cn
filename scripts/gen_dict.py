def build():
    # 单字：拼音 -> [汉字]。先收一级(常用)，再收二级(次常用/生僻)
    by_pinyin: dict[str, list[str]] = defaultdict(list)
    seen_chars: set[str] = set()
    char_level: dict[str, int] = {}
    for level, source in ((1, gb2312_level1), (2, gb2312_level2)):
        for ch in source():
            if not re.match(r"[\u4e00-\u9fff]", ch) or ch in seen_chars:
                continue
            seen_chars.add(ch)
            py = pinyin(ch, style=Style.NORMAL, heteronym=False, errors="ignore")
            if not py or not py[0]:
                continue
            syl = re.sub(r"[^a-z]", "", py[0][0].lower())
            if syl:
                by_pinyin[syl].append(ch)
                char_level[ch] = level

    # 高频字权重：让常用字排在同音候选的前面
    freq_order: dict[str, int] = {}
    for i, ch in enumerate(HIGH_FREQ.strip()):
        if ch.strip() and ch not in freq_order:
            freq_order[ch] = i

    MAX_CHARS = MAX_CHARS_PER_SYLLABLE
    char_dict: dict[str, str] = {}
    for syl, chars in by_pinyin.items():
        # 1) 一级字优先（常用字不会排在生僻字后面）
        # 2) 高频字优先（同音字里最常用的排前）
        # 3) 其余保持 GB2312 原序（sort 稳定，不打乱顺序）
        chars.sort(
            key=lambda c: (
                char_level.get(c, 2),
                0 if c in freq_order else 1,
                freq_order.get(c, 0),
            )
        )
        char_dict[syl] = "".join(chars[:MAX_CHARS])

    # 词组
    word_dict: dict[str, list[str]] = defaultdict(list)
    # 首字母缩写（简拼）索引：bj -> 北京 / 比较 ...
    abbr_dict: dict[str, list[str]] = defaultdict(list)
    for w in iter_words():
        w = w.strip()
        if len(w) < 2 or len(w) > 8 or not all("\u4e00" <= c <= "\u9fff" for c in w):
            continue
        py = pinyin(w, style=Style.NORMAL, heteronym=False, errors="ignore")
        if len(py) != len(w):
            continue
        key = "".join(p[0] for p in py if p)
        if not key.isalpha():
            continue
        if w not in word_dict[key]:
            word_dict[key].append(w)

        # 简拼：每个音节取首字母，如 北京 bei+jing -> bj
        abbr = "".join(p[0][0] for p in py if p and p[0])
        if len(abbr) >= 2 and w not in abbr_dict[abbr]:
            abbr_dict[abbr].append(w)
        # 单字母索引：只打一个首字母也要能出词，如 z -> 中国 / 准备
        if w not in abbr_dict[abbr[:1]]:
            abbr_dict[abbr[:1]].append(w)

    # 简拼候选排序：优选词优先，其余保持词表原顺序；排序后再截断
    for k, words in abbr_dict.items():
        if len(k) == 1:
            continue
        words.sort(key=lambda w: _ABBR_PRIORITY.get(w, 9999))
        abbr_dict[k] = words[:MAX_WORDS_PER_ABBR]

    # 单字母键：只留少量高频词，排在「联想字」后面作为补充；
    # 主视觉交给下面生成的 INITIAL_CHAR_DICT（大量常用单字）。
    for initial, words in abbr_dict.items():
        if len(initial) != 1:
            continue
        words.sort(key=lambda w: _ABBR_PRIORITY.get(w, 9999))
        abbr_dict[initial] = words[:INITIAL_WORDS_PER_KEY]

    # 首字母 -> 联想字：把字表按声母聚合，按「一级常用字优先 + 语料字频」全局排序。
    # 只打 b / q / n 一个字母时，候选栏就给出这个声母下尽可能多的常用单字。
    initial_pool: dict[str, set[str]] = defaultdict(set)
    for syl, chars in char_dict.items():
        for ch in chars:
            initial_pool[syl[0]].add(ch)
    initial_char_dict: dict[str, str] = {}
    for initial, pool in initial_pool.items():
        ranked = sorted(
            pool,
            key=lambda c: (
                char_level.get(c, 2),
                0 if c in freq_order else 1,
                freq_order.get(c, 0),
            ),
        )
        initial_char_dict[initial] = "".join(ranked[:MAX_CHARS_PER_INITIAL])

    # 音节全拼补字：把每个音节的全字表按字频排在简拼候选后面，
    # 这样打全 "nv" 也能选到"女"，而不是只在简拼词表里打转。
    # 单字母音节（a / e / o）已有 INITIAL_CHAR_DICT，无需再补。
    for syll, chars in char_dict.items():
        if len(syll) == 1:
            continue
        extra = [c for c in chars if c not in abbr_dict[syll]]
        if not extra:
            continue
        abbr_dict[syll].extend(extra[:MAX_CHARS_PER_FULL_SYLLABLE])

    return char_dict, word_dict, abbr_dict, initial_char_dict


