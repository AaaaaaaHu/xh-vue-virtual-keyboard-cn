# ---------------------------------------------------------------- 1. 汉字来源
def gb2312_level1() -> list[str]:
    """GB2312 一级汉字区：3755 个常用字，按拼音排序。"""
    chars = []
    for hi in range(0xB0, 0xD8):
        for lo in range(0xA1, 0xFF):
            try:
                chars.append(bytes([hi, lo]).decode("gb2312"))
            except UnicodeDecodeError:
                continue
    return chars


def gb2312_level2() -> list[str]:
    """GB2312 二级汉字区：3008 个次常用字，按部首排序。

    人名、地名里的生僻字多在这里（例如 堃 玥 珺 淼 燚），
    政务 / 医疗场景录名字时常需要。
    """
    chars = []
    for hi in range(0xD8, 0xF8):
        for lo in range(0xA1, 0xFF):
            try:
                chars.append(bytes([hi, lo]).decode("gb2312"))
            except UnicodeDecodeError:
                continue
    return chars


